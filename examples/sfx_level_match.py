def family_of(name: str) -> str:
    for fam, names in NAME_FAMILY.items():
        if name in names.split():
            return fam
    return MODULE_FAMILY.get(S.REGISTRY[name]["fn"].__module__.replace("genny.", ""), "foley")


def measure(name: str) -> float | None:
    np.random.seed(0)
    y = np.asarray(S.render_sfx(name, SR), float)
    return round(rms_db(y, SR), 2) if np.all(np.isfinite(y)) else None


def write_table(measured: dict[str, float | None]) -> int:
    rows, failed = [], []
    for name in sorted(S.REGISTRY):
        m = measured.get(name)
        if m is None:
            failed.append(name)
            continue
        target = FAMILY_DB[family_of(name)]
        rows.append((name, m, target, round(target - m, 2) if m > -100.0 else 0.0))
    body = "\n".join(f'    "{n}": ({m}, {t}, {g}),' for n, m, t, g in rows)
    src = ('"""Relative levels of the sound effects (generated by examples/sfx_level_match.py; do not edit by hand).\n\n'
           "LEVELS[name] = (measured, target, gain): the RMS dBFS of the loudest 400 ms of the default render, the level of its\n"
           'family, and the gain in dB that brings the first to the second. `level="match"` applies that gain.\n"""\n'
           f"LEVELS: dict[str, tuple[float, float, float]] = {{\n{body}\n}}\n"
           "GAIN_DB: dict[str, float] = {k: v[2] for k, v in LEVELS.items()}\n"
           f"UNMEASURED: tuple[str, ...] = {tuple(failed)!r}\n")
    (ROOT / "genny" / "_sfx_levels.py").write_text(src, encoding="utf-8", newline="\n")
    return len(rows)


def main():
    a = sys.argv[1:]
    check = "--check" in a
    names = sorted(S.REGISTRY)
    if "--part" in a:
        k, n = (int(v) for v in a[a.index("--part") + 1].split("/"))
        names = names[k - 1::n]
    if "--from" in a:
        measured: dict = {}
        for f in a[a.index("--from") + 1:]:
            if f.startswith("--"):
                break
            measured.update(json.loads(Path(f).read_text(encoding="utf-8")))
    else:
        measured = {}
        for name in names:
            t = time.time()
            try:
                measured[name] = measure(name)
            except Exception as e:  # noqa: BLE001
                measured[name] = None
                print(f"{name}: FAILED {type(e).__name__}: {e}", flush=True)
            print(f"{name:<28} {measured[name]} dB  ({time.time() - t:.1f}s)", flush=True)
    if "--out" in a:
        Path(a[a.index("--out") + 1]).write_text(json.dumps(measured), encoding="utf-8")
        return
    if check:
        from genny import _sfx_levels as L
        worst = 0.0
        for name, m in measured.items():
            if m is None or name not in L.LEVELS:
                print(f"{name:<28} missing")
                continue
            d = m - L.LEVELS[name][0]
            worst = max(worst, abs(d))
            if abs(d) > 0.05:
                print(f"{name:<28} table {L.LEVELS[name][0]:7.2f}  now {m:7.2f}  ({d:+.2f})")
        print(f"{len(measured)} checked, worst gap {worst:.2f} dB")
        return
    print(f"wrote {write_table(measured)} levels to genny/_sfx_levels.py")


if __name__ == "__main__":
    main()
