# Harmonoise source model, category 1 (cars), third-octave bands 20 Hz .. 12.5 kHz: Jonasson et al.,
# "Source modelling of road vehicles", SP Swedish National Testing and Research Institute, 2004.
# Rolling L = aR + bR log10(v / 70 km/h); propulsion L = aP + bP (v - 70) / 70.
_HN_F = 20.0 * 2.0 ** (np.arange(29) / 3.0)
_HN_AR = np.array([69.9, 69.9, 69.9, 74.9, 74.9, 74.9, 79.3, 82.5, 81.3, 80.9, 78.9, 78.8, 80.5, 85.7, 87.7, 89.2, 90.6,
                   89.9, 89.4, 87.6, 85.6, 82.5, 79.6, 76.8, 74.5, 71.9, 69.0, 69.0, 69.0])
_HN_BR = np.array([33.0, 33.0, 33.0, 30.0, 30.0, 30.0, 41.0, 41.2, 42.3, 41.8, 38.6, 35.5, 31.7, 21.5, 21.2, 23.5, 29.1,
                   33.5, 34.1, 35.1, 36.4, 37.4, 38.9, 39.7, 39.7, 39.7, 39.7, 39.7, 39.7])
_HN_AP = np.array([85.8, 87.6, 97.5, 87.5, 96.6, 97.2, 91.5, 86.7, 86.8, 84.9, 86.0, 86.0, 85.9, 80.6, 80.2, 77.8, 78.0,
                   81.4, 82.3, 82.6, 81.5, 80.7, 78.8, 77.0, 76.0, 74.0, 72.0, 72.0, 72.0])
_HN_BP = np.where(_HN_F < 195.0, 0.0, 8.2)


def road_noise_levels(kmh: float) -> tuple[np.ndarray, np.ndarray]:
    """(rolling, propulsion) sound power levels in dB per third-octave band of ``_HN_F``."""
    v = max(float(kmh), 1.0)
    return _HN_AR + _HN_BR * np.log10(v / 70.0), _HN_AP + _HN_BP * (v - 70.0) / 70.0


def _third_octave_noise(n: int, rng, levels_db: np.ndarray) -> np.ndarray:
    """Noise with the given third-octave band levels: a band of constant level has a power density
    falling as 1 / f, so the spectrum is shaped by the interpolated level minus 10 log10 f."""
    f = np.maximum(np.fft.rfftfreq(n, 1.0 / SR), 1.0)
    g = np.interp(np.log(f), np.log(_HN_F), levels_db, left=levels_db[0] - 30.0, right=levels_db[-1] - 30.0)
    return np.fft.irfft(np.fft.rfft(rng.standard_normal(n)) * 10 ** ((g - 10 * np.log10(f)) / 20.0), n)


