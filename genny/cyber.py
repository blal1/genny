# ENGINE AS WAVEGUIDES, TURBO, TYRES, PASS-BY
# =============================================================================================
# Baldan, Lachambre, Delle Monache & Boussard, "Physically informed car engine sound synthesis for
# virtual and augmented environments" (SIVE 2015), as implemented by Antonio-R1/engine-sound-generator
# and DasEtwas/enginesound: over one 720 degree cycle x in [0, 1) each cylinder has
#   intake valve   sin(4 pi x)              on 0    < x < 0.25
#   exhaust valve  -sin(4 pi x)             on 0.75 < x < 1
#   piston         cos(4 pi x)
#   ignition       sin(2 pi (x - 0.5) / t)  on 0.5  < x < 0.5 + t / 2
# and feeds an intake and an exhaust waveguide whose reflection at the cylinder end follows the valve:
# r = r_open v + r_closed (1 - v). The exhausts join in a collector, a straight pipe and a muffler
# of four short parallel guides. Constants are DasEtwas' default.esc unless marked.
# Left out of the paper's model: the cylinder itself as a waveguide whose length follows the piston
# (cylinder volume and compression ratio), and the outlet pipe after the muffler. Backfire is the
# paper's: while the engine revs down, each cycle fires an ignition-shaped pulse into the exhaust
# with a probability that is multiplied by itself after every pop.

@numba.njit(cache=True)
def _pipe_engine_k(inc, offs, noise, pops, n_ex, n_in, n_pipe, n_muf, pf, igf, ign_t):
    n, C = len(inc), len(offs)
    exu, exl = np.zeros((C, n_ex.max())), np.zeros((C, n_ex.max()))
    inu, inl = np.zeros((C, n_in)), np.zeros((C, n_in))
    pu, pl = np.zeros(n_pipe), np.zeros(n_pipe)
    mu, ml = np.zeros((4, n_muf.max())), np.zeros((4, n_muf.max()))
    out = np.zeros((3, n))                                   # intake, exhaust, block vibration
    x = 0.0
    back = 0.0                                               # wave returning from the pipe into the headers
    for t in range(n):
        x = (x + inc[t]) % 1.0
        coll, intake, vib = 0.0, 0.0, 0.0
        for c in range(C):
            xc = (x + offs[c]) % 1.0
            iv = math.sin(4 * math.pi * xc) if xc < 0.25 else 0.0
            ev = -math.sin(4 * math.pi * xc) if xc > 0.75 else 0.0
            cyl = pf * math.cos(4 * math.pi * xc)
            if 0.5 < xc < 0.5 + ign_t / 2:
                cyl += igf * math.sin(2 * math.pi * (xc - 0.5) / ign_t)
            vib += cyl
            # exhaust guide: left end = valve, right end = collector
            i = t % n_ex[c]
            r = 0.01 * ev + 0.7145 * (1.0 - ev)
            u, lo = exu[c, i], exl[c, i]
            exu[c, i] = (1.0 - r) * cyl * 0.5 + r * lo
            exl[c, i] = back / C + 0.06 * u
            coll += u * 0.94
            # intake guide: left end = open air (inverting), right end = valve
            i = t % n_in
            r = 0.006 * iv + 1.0 * (1.0 - iv)
            u, lo = inu[c, i], inl[c, i]
            inu[c, i] = -0.7576 * lo
            inl[c, i] = (1.0 - r) * cyl * 0.5 + noise[t] * iv + r * u
            intake += lo * 1.7576
        i = t % n_pipe
        u, lo = pu[i], pl[i]
        pu[i] = coll / C + pops[t] + 0.0617 * lo
        back = lo * (1.0 - 0.0617)
        ret, ex = 0.0, 0.0
        for j in range(4):
            k = t % n_muf[j]
            a, b = mu[j, k], ml[j, k]
            mu[j, k] = u * 0.25
            ml[j, k] = -0.142 * a
            ex += a * 1.142
            ret += b
        pl[i] = ret
        out[0, t], out[1, t], out[2, t] = intake, ex, vib
    return out


