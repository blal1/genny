"""Export helpers: scripts that carry rendered files into a game audio tool."""
from __future__ import annotations

import json
import socket
from pathlib import Path

FMOD_PORT = 3663           # command port of FMOD Studio's scripting console


def fmod_import_script(paths, events=True, prefix="") -> str:
    """JavaScript for FMOD Studio's scripting API (studio.project): imports each WAV (`importAudioFile`) and, with
    `events`, makes one event per file holding a single sound on its own audio track, named `prefix` + the file name.
    Run it from Studio's Scripts menu, or send it with `fmod_send`."""
    lines = ["// generated by genny: import rendered files", "var made = [];"]
    for p in paths:
        p = Path(p)
        path = json.dumps(str(p.resolve()).replace("\\", "/"))
        name = json.dumps(prefix + p.stem)
        lines.append(f"var a = studio.project.importAudioFile({path});")
        if events:
            lines += [f"var e = studio.project.create('Event'); e.name = {name};",
                      "var t = e.addGroupTrack(); var s = t.addSound(e.timeline, 'SingleSound', 0, a.length);",
                      "s.audioFile = a; made.push(e);"]
    lines.append("made.length;")
    return "\n".join(lines) + "\n"


def fmod_send(script: str, host: str = "127.0.0.1", port: int = FMOD_PORT, timeout: float = 5.0) -> str:
    """Send a script to a running FMOD Studio over its scripting TCP port and return what it answers."""
    with socket.create_connection((host, int(port)), timeout=timeout) as s:
        s.sendall(script.encode("utf-8") + b"\0")
        s.settimeout(timeout)
        try:
            return s.recv(65536).decode("utf-8", "replace")
        except socket.timeout:
            return ""
