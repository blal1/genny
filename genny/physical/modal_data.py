def _pd_parse(path: Path) -> dict:
    """Parse a .pd file into nested canvases {objs: [...], conns: [(src, out, dst, in)], name}."""
    text = path.read_text(encoding="utf-8", errors="replace")
    records = re.split(r"(?<!\\);\s*\n", text)
    stack: list[dict] = []
    root = None
    for rec in records:
        rec = " ".join(rec.split())
        if not rec:
            continue
        if rec.startswith("#N canvas"):
            c = {"objs": [], "conns": [], "name": None}
            if root is None:
                root = c
            stack.append(c)
            continue
        if not rec.startswith("#X "):
            continue
        parts = rec.split(" ")
        kind = parts[1]
        if kind == "restore":
            c = stack.pop()
            c["name"] = " ".join(parts[5:]) if len(parts) > 5 else ""
            stack[-1]["objs"].append({"kind": "pd", "x": float(parts[2]), "y": float(parts[3]),
                                      "text": " ".join(parts[4:]), "canvas": c})
        elif kind == "connect":
            stack[-1]["conns"].append(tuple(int(p) for p in parts[2:6]))
        elif kind in ("obj", "msg", "floatatom", "symbolatom", "listbox", "text"):
            stack[-1]["objs"].append({"kind": kind, "x": float(parts[2]), "y": float(parts[3]),
                                      "text": " ".join(parts[4:])})
    return root


def _pd_find(c: dict, name: str) -> list[dict]:
    """All sub-canvases (recursively) whose restore text is 'pd <name>'."""
    found = []
    for o in c["objs"]:
        if o["kind"] == "pd":
            if o["canvas"]["name"] == name:
                found.append(o["canvas"])
            found += _pd_find(o["canvas"], name)
    return found


