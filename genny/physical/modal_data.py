def _fmt(v, indent=8) -> str:
    if isinstance(v, dict):
        pad = " " * indent
        inner = ",\n".join(f"{pad}{k!r}: {_fmt(x, indent + 4)}" for k, x in v.items())
        return "{\n" + inner + "\n" + " " * (indent - 4) + "}"
    if isinstance(v, list) and v and isinstance(v[0], list):
        pad = " " * indent
        return "[\n" + ",\n".join(pad + _fmt(r, indent + 4) for r in v) + ",\n" + " " * (indent - 4) + "]"
    if isinstance(v, list) and v and isinstance(v[0], dict):
        pad = " " * indent
        return "[\n" + ",\n".join(pad + _fmt(r, indent + 4) for r in v) + ",\n" + " " * (indent - 4) + "]"
    return repr(v)


def _render(tables: dict) -> str:
    lines = []
    for name, t in tables.items():
        lines.append(f"{name.upper()} = {_fmt(t, 4)}\n")
    lines.append("TABLES = {\n" + "".join(f"    {n!r}: {n.upper()},\n" for n in tables) + "}\n")
    return "\n".join(lines)


def _write() -> None:
    path = Path(__file__)
    src = path.read_text(encoding="utf-8")
    a = src.index("# BEGIN GENERATED")
    a = src.index("\n", a) + 1
    b = src.index("# END GENERATED")
    new = src[:a] + _render(extract_all()) + src[b:]
    path.write_text(new, encoding="utf-8")


def _verify() -> int:
    fresh = extract_all()
    lit = all_tables()
    bad = 0
    for name, t in fresh.items():
        if lit.get(name) != t:
            print(f"MISMATCH {name}")
            bad += 1
    print(f"{len(fresh)} tables extracted, {len(lit)} literal, {bad} mismatches")
    for name, t in lit.items():
        n = len(t.get("freqs") or t.get("ratios") or t.get("samples_int16") or t.get("groups") or [])
        pos = len(t["gains"]) if "gains" in t else "-"
        print(f"  {name:28s} kind={t['kind']:15s} modes={n!s:4s} positions={pos}")
    return bad


if __name__ == "__main__":
    if "--write" in sys.argv:
        _write()
        print("written")
    else:
        sys.exit(1 if _verify() else 0)
