def _read_sy(path: Path) -> dict:
    lines = [ln.strip() for ln in path.read_text().splitlines() if ln.strip()]
    it = iter(lines)

    def val(label):  # ModalModel.readModes reads positionally; the label text varies per file
        assert next(it).endswith(":"), label
        return next(it)

    nact = int(val("nactive_freq"))
    nf = int(val("n_freq"))
    npnt = int(val("n_points"))
    fs = float(val("freq_scale"))
    ds = float(val("d_scale"))
    as_ = float(val("a_scale"))
    assert next(it).startswith("frequencies")
    f = [float(next(it)) for _ in range(nf)]
    assert next(it).startswith("dampings")
    d = [float(next(it)) for _ in range(nf)]
    assert next(it).startswith("amplitudes")
    a = [[float(next(it)) for _ in range(nf)] for _ in range(npnt)]
    return dict(kind="vdd", freqs=f[:nact], decays=d[:nact], gains=[row[:nact] for row in a],
                fscale=fs, dscale=ds, ascale=as_, n_freq_in_file=nf,
                source=f"modalpaper-src/java/{path.name} (first nactive_freq={nact} modes)")


